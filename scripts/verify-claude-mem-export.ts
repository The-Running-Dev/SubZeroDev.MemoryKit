const requests: { url: string; body?: unknown }[] = [];
const epoch = Date.parse('2026-11-01T00:00:00Z');
class FixtureDate extends Date {
  constructor() {
    super(epoch);
  }
  static now() {
    return epoch;
  }
}
const context = createContext({
  URLSearchParams,
  AbortController,
  setTimeout,
  clearTimeout,
  Date: FixtureDate,
  process: { env: { CLAUDE_MEM_EXPORT_MEMORIES_NO_MAIN: '1' }, argv: [] },
  console: { log() {}, error() {} },
  fetch: async (address: string, init?: RequestInit) => {
    requests.push({ url: address, ...(init?.body ? { body: JSON.parse(String(init.body)) } : {}) });
    return {
      ok: true,
      json: async () =>
        address.includes('/api/search?')
          ? { observations, sessions: summaries, prompts }
          : sessions,
    };
  },
});
const modules: Record<string, Record<string, unknown>> = {
  fs: { statSync, writeFileSync },
  path: { join },
  url: { pathToFileURL },
  '../src/shared/SettingsDefaultsManager.js': {
    SettingsDefaultsManager: {
      loadFromFile: () => ({
        CLAUDE_MEM_WORKER_HOST: '127.0.0.1',
        CLAUDE_MEM_WORKER_PORT: '37777',
      }),
    },
  },
  '../src/shared/paths.js': { resolveDataDir: () => '/synthetic-only' },
  '../src/shared/atomic-json.js': {
    writeJsonFileAtomic: (path: string, data: unknown) =>
      writeFileSync(path, JSON.stringify(data, null, 2) + '\n'),
  },
  '../src/shared/worker-url.js': { formatHostForUrl: (host: string) => host },
};
const compiled = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
}).outputText;
const exporter = new SourceTextModule(compiled, { context, identifier: url });
await exporter.link(async (specifier) => {
  const exports = modules[specifier];
  assert.ok(exports, `Unexpected upstream import: ${specifier}`);
  return new SyntheticModule(
    Object.keys(exports),
    function () {
      for (const [key, value] of Object.entries(exports)) this.setExport(key, value);
    },
    { context }
  );
});
await exporter.evaluate();
await (
  exporter.namespace as unknown as {
    exportMemories: (q: string, p: string, project: string) => Promise<void>;
  }
).exportMemories('Cobalt', destination, 'synthetic-alpha');
assert.equal(requests.length, 2);
